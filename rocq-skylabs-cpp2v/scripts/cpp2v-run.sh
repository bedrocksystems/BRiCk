#!/usr/bin/env bash
# Execute a command using a recorded host/container toolchain configuration.
set -euo pipefail

fail() { echo "cpp2v-run: $*" >&2; exit 2; }
config=
host_tool=
container_tool=
flags_file=
workspace=
forward=()
extra_mounts=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        --config|--host-tool|--container-tool|--flags-file|--workspace|--env|--mount)
            [[ $# -ge 2 ]] || fail "missing value for $1"
            case "$1" in
                --config) config=$2 ;;
                --host-tool) host_tool=$2 ;;
                --container-tool) container_tool=$2 ;;
                --flags-file) flags_file=$2 ;;
                --workspace) workspace=$2 ;;
                --env)
                    [[ $2 =~ ^[a-zA-Z_][a-zA-Z_0-9]*$ ]] || fail "invalid environment variable: $2"
                    forward+=("$2")
                    ;;
                --mount) extra_mounts+=("$2") ;;
            esac
            shift 2
            ;;
        --) shift; break ;;
        *) fail "unknown option: $1" ;;
    esac
done
[[ -n $config && -r $config ]] || fail "--config must name a readable toolchain configuration"
[[ $config == /* ]] || config="$PWD/$config"
# This is a trusted, shell-quoted configuration generated by cpp2v-toolchain.
cpp_env_version='' cpp_env_mode='' cpp_env_image='' cpp_env_workspace=''
cpp_env_user='' cpp_env_platform='' cpp_env_opam=''
# shellcheck disable=SC1090
source "$config"
[[ ${cpp_env_version:-} == 1 ]] || fail "unsupported toolchain configuration"

if [[ -n $host_tool ]]; then
    container_tool=${container_tool:-${host_tool##*/}}
else
    [[ $# -gt 0 ]] || fail "expected a command after --"
    host_tool=$1
    container_tool=${container_tool:-$1}
    shift
fi

enabled=$cpp_env_mode
case "$enabled" in
    n|y) ;;
    if-libstdc++)
        enabled=n
        if [[ -n $flags_file ]]; then
            [[ -r $flags_file ]] || fail "cannot read flags file: $flags_file"
            if grep -Fxq -- '-stdlib=libstdc++' "$flags_file"; then enabled=y; fi
        else
            for arg in "$@"; do
                if [[ $arg == -stdlib=libstdc++ ]]; then enabled=y; break; fi
            done
        fi
        ;;
    *) fail "invalid toolchain mode: $enabled" ;;
esac
if [[ $enabled == n ]]; then
    exec "$host_tool" "$@"
fi

command -v docker >/dev/null 2>&1 || fail "Docker is required by the selected toolchain"
[[ -n $cpp_env_image ]] || fail "the selected toolchain has no Docker image"
workspace=${workspace:-$cpp_env_workspace}
[[ -d $workspace ]] || fail "workspace does not exist: $workspace"
workspace=$(cd "$workspace" && pwd -P)
cwd=$(pwd -P)
args=(run --rm --user "$cpp_env_user" --env HOME=/tmp
      --volume "$workspace:$workspace" --workdir "$cwd")
if [[ -n $cpp_env_platform ]]; then args+=(--platform "$cpp_env_platform"); fi
mounted=("$workspace")

add_mount() {
    local directory=$1 destination existing
    [[ -d $directory ]] || fail "mount directory does not exist: $directory"
    # Keep the command's logical path as the destination, even for symlinks.
    # Relative mounts are resolved from the physical container working dir.
    destination=$(cd "$cwd" && cd -L -- "$directory" && pwd -L)
    directory=$(cd -P -- "$destination" && pwd -P)
    for existing in "${mounted[@]}"; do
        if [[ $destination == "$existing" ]]; then return; fi
    done
    args+=(--volume "$directory:$destination")
    mounted+=("$destination")
}
# Preserve absolute paths and the working directory, including editor-generated
# inputs outside the workspace. No assumptions about input/output suffixes.
case "$cwd/" in "$workspace/"*) ;; *) add_mount "$cwd" ;; esac
if [[ ${#extra_mounts[@]} -gt 0 ]]; then
    for path in "${extra_mounts[@]}"; do
        if [[ -f $path ]]; then path=$(dirname "$path"); fi
        add_mount "$path"
    done
fi
# The container command belongs to the image (e.g. /bin/sh), not the host.
# External executables can be shared explicitly with --mount.
for path in "$@"; do
    if [[ $path == /* && -f $path ]]; then add_mount "$(dirname "$path")"; fi
done
if [[ ${#forward[@]} -gt 0 ]]; then
    for var in "${forward[@]}"; do
        if printenv "$var" >/dev/null; then args+=(--env "$var"); fi
    done
fi

if [[ $cpp_env_opam == y ]]; then
    exec docker "${args[@]}" "$cpp_env_image" /bin/bash -ec \
        'opam_env=$(opam env); eval "$opam_env"; exec "$@"' cpp2v-run "$container_tool" "$@"
fi
exec docker "${args[@]}" "$cpp_env_image" "$container_tool" "$@"
